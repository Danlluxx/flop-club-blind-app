function mapBlindLevels(items: BlindLevelInput[]): BlindLevel[] {
  return items.map((item) =>
    Array.isArray(item)
      ? {
          level: item[0],
          smallBlind: item[1],
          bigBlind: item[2],
          bigBlindAnte: item[3],
          minutes: item[4],
        }
      : item,
  );
}

