export type BlindLevel = {
  type?: "level" | "break";
  level: number;
  smallBlind: number;
  bigBlind: number;
  bigBlindAnte: number;
  minutes: number;
  label?: string;
  note?: string;
};

export type BlindStructure = {
  id: string;
  name: string;
  levels: BlindLevel[];
};

